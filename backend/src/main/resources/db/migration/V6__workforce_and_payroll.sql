-- Every employee can read their own payslips and apply for leave.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN (VALUES
    ('PROJECT_MANAGER', 'PAYROLL', 'VIEW'), ('PROJECT_MANAGER', 'LEAVE', 'CREATE'),
    ('ACCOUNTANT', 'LEAVE', 'VIEW'), ('ACCOUNTANT', 'LEAVE', 'CREATE')
) AS g(role_name, module, action) ON r.name = g.role_name
JOIN permissions p ON p.module = g.module AND p.action = g.action
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- ---- Shifts -------------------------------------------------------------------
CREATE TABLE shifts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    start_time  TIME         NOT NULL,
    end_time    TIME         NOT NULL,
    description VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by  BIGINT,
    CONSTRAINT ck_shifts_times CHECK (end_time > start_time)
);

CREATE UNIQUE INDEX ux_shifts_name ON shifts (LOWER(name));

