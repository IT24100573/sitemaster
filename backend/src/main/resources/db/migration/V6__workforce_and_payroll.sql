-- ---- Attendance and overtime ----------------------------------------------------
CREATE TABLE attendance (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT       NOT NULL REFERENCES employees (id),
    project_id       BIGINT       NOT NULL REFERENCES projects (id),
    shift_id         BIGINT REFERENCES shifts (id),
    attendance_date  DATE         NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    check_in         TIMESTAMP,
    check_out        TIMESTAMP,
    hours_worked     NUMERIC(5, 2),
    verified         BOOLEAN      NOT NULL DEFAULT FALSE,
    verified_by_id   BIGINT REFERENCES users (id),
    verified_at      TIMESTAMP,
    marked_by_id     BIGINT       NOT NULL REFERENCES users (id),
    notes            VARCHAR(500),
    created_at       TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by       BIGINT,
    CONSTRAINT uq_attendance_employee_date UNIQUE (employee_id, attendance_date),
    CONSTRAINT ck_attendance_status CHECK (status IN ('PRESENT', 'ABSENT', 'HALF_DAY', 'ON_LEAVE')),
    CONSTRAINT ck_attendance_times CHECK (check_out IS NULL OR check_in IS NULL OR check_out > check_in),
    CONSTRAINT ck_attendance_hours CHECK (hours_worked IS NULL OR (hours_worked >= 0 AND hours_worked <= 16))
);

CREATE INDEX ix_attendance_project_date ON attendance (project_id, attendance_date);
CREATE INDEX ix_attendance_date ON attendance (attendance_date);

CREATE TABLE overtime (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id   BIGINT        NOT NULL REFERENCES attendance (id) ON DELETE CASCADE,
    hours           NUMERIC(4, 2) NOT NULL,
    reason          VARCHAR(500),
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    recorded_by_id  BIGINT        NOT NULL REFERENCES users (id),
    decided_by_id   BIGINT REFERENCES users (id),
    decided_at      TIMESTAMP,
    decision_note   VARCHAR(500),
    created_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT uq_overtime_attendance UNIQUE (attendance_id),
    CONSTRAINT ck_overtime_hours CHECK (hours > 0 AND hours <= 8),
    CONSTRAINT ck_overtime_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- ---- Leave ---------------------------------------------------------------------
CREATE TABLE leave_types (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  NOT NULL,
    name            VARCHAR(50)  NOT NULL,
    days_per_year   NUMERIC(5, 1),
    paid            BOOLEAN      NOT NULL DEFAULT TRUE,
    backdate_days   INTEGER      NOT NULL DEFAULT 0,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT uq_leave_types_code UNIQUE (code),
    CONSTRAINT ck_leave_types_days CHECK (days_per_year IS NULL OR (days_per_year >= 0 AND days_per_year <= 365)),
    CONSTRAINT ck_leave_types_backdate CHECK (backdate_days BETWEEN 0 AND 31)
);

