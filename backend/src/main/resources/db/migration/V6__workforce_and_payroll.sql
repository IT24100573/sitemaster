CREATE TABLE leave_balances (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT        NOT NULL REFERENCES employees (id),
    leave_type_id  BIGINT        NOT NULL REFERENCES leave_types (id),
    year           INTEGER       NOT NULL,
    entitled_days  NUMERIC(5, 1) NOT NULL,
    used_days      NUMERIC(5, 1) NOT NULL DEFAULT 0,
    created_at     TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by     BIGINT,
    CONSTRAINT uq_leave_balances UNIQUE (employee_id, leave_type_id, year),
    CONSTRAINT ck_leave_balances_days CHECK (entitled_days >= 0 AND used_days >= 0 AND used_days <= entitled_days)
);

CREATE TABLE leave_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT        NOT NULL REFERENCES employees (id),
    leave_type_id    BIGINT        NOT NULL REFERENCES leave_types (id),
    from_date        DATE          NOT NULL,
    to_date          DATE          NOT NULL,
    days             NUMERIC(5, 1) NOT NULL,
    reason           VARCHAR(500)  NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    requested_by_id  BIGINT        NOT NULL REFERENCES users (id),
    approved_by_id   BIGINT REFERENCES users (id),
    remarks          VARCHAR(2000),
    decided_at       TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at       TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by       BIGINT,
    CONSTRAINT ck_leave_requests_dates CHECK (to_date >= from_date),
    CONSTRAINT ck_leave_requests_days CHECK (days > 0),
    CONSTRAINT ck_leave_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX ix_leave_requests_employee ON leave_requests (employee_id, from_date);

-- ---- Contracts and training ----------------------------------------------------------
CREATE TABLE contracts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       BIGINT         NOT NULL REFERENCES employees (id),
    contract_no       VARCHAR(30)    NOT NULL,
    title             VARCHAR(150)   NOT NULL,
    start_date        DATE           NOT NULL,
    end_date          DATE           NOT NULL,
    contract_value    NUMERIC(14, 2),
    notes             VARCHAR(500),
    file_id           BIGINT REFERENCES stored_files (id),
    reminder_sent_at  TIMESTAMP,
    created_at        TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at        TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by        BIGINT,
    CONSTRAINT uq_contracts_number UNIQUE (contract_no),
    CONSTRAINT ck_contracts_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_contracts_value CHECK (contract_value IS NULL OR contract_value > 0)
);

CREATE INDEX ix_contracts_end ON contracts (end_date);

CREATE TABLE training_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT       NOT NULL REFERENCES employees (id),
    title         VARCHAR(150) NOT NULL,
    provider      VARCHAR(150),
    safety        BOOLEAN      NOT NULL DEFAULT FALSE,
    completed_on  DATE         NOT NULL,
    expires_on    DATE,
    notes         VARCHAR(500),
    file_id       BIGINT REFERENCES stored_files (id),
    created_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT ck_training_dates CHECK (expires_on IS NULL OR expires_on >= completed_on)
);

-- ---- Payroll ----------------------------------------------------------------------------
CREATE TABLE payroll_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year               INTEGER        NOT NULL,
    month              INTEGER        NOT NULL,
    status             VARCHAR(20)    NOT NULL DEFAULT 'SUMMARY_SENT',
    working_days       INTEGER        NOT NULL,
    summary_sent_by_id BIGINT         NOT NULL REFERENCES users (id),
    summary_sent_at    TIMESTAMP      NOT NULL,
    calculated_by_id   BIGINT REFERENCES users (id),
    calculated_at      TIMESTAMP,
    paid_at            TIMESTAMP,
    total_gross        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_deductions   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_net          NUMERIC(14, 2) NOT NULL DEFAULT 0,
    created_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by         BIGINT,
    CONSTRAINT uq_payroll_runs_month UNIQUE (year, month),
    CONSTRAINT ck_payroll_runs_month CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_payroll_runs_status CHECK (status IN ('SUMMARY_SENT', 'CALCULATED', 'PAID'))
);

CREATE TABLE payroll_summaries (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id    BIGINT        NOT NULL REFERENCES payroll_runs (id) ON DELETE CASCADE,
    employee_id       BIGINT        NOT NULL REFERENCES employees (id),
    employment_type   VARCHAR(20)   NOT NULL,
    present_days      INTEGER       NOT NULL,
    half_days         INTEGER       NOT NULL,
    absent_days       INTEGER       NOT NULL,
    paid_leave_days   NUMERIC(5, 1) NOT NULL,
    unpaid_leave_days NUMERIC(5, 1) NOT NULL,
    overtime_hours    NUMERIC(6, 2) NOT NULL,
    created_at        TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at        TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by        BIGINT,
    CONSTRAINT uq_payroll_summaries UNIQUE (payroll_run_id, employee_id),
    CONSTRAINT ck_payroll_summaries_values CHECK (present_days >= 0 AND half_days >= 0 AND absent_days >= 0
        AND paid_leave_days >= 0 AND unpaid_leave_days >= 0 AND overtime_hours >= 0)
);

CREATE TABLE payslips (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id    BIGINT         NOT NULL REFERENCES payroll_runs (id) ON DELETE CASCADE,
    employee_id       BIGINT         NOT NULL REFERENCES employees (id),
    employment_type   VARCHAR(20)    NOT NULL,
    gross_pay         NUMERIC(14, 2) NOT NULL,
    total_deductions  NUMERIC(14, 2) NOT NULL,
    net_pay           NUMERIC(14, 2) NOT NULL,
    paid              BOOLEAN        NOT NULL DEFAULT FALSE,
    paid_at           TIMESTAMP,
    payment_method    VARCHAR(20),
    payment_reference VARCHAR(50),
    created_at        TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at        TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by        BIGINT,
    CONSTRAINT uq_payslips UNIQUE (payroll_run_id, employee_id),
    CONSTRAINT ck_payslips_net CHECK (net_pay >= 0),
    CONSTRAINT ck_payslips_paid CHECK (paid = (paid_at IS NOT NULL)),
    CONSTRAINT ck_payslips_method CHECK (payment_method IS NULL OR payment_method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE'))
);

CREATE TABLE payslip_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payslip_id     BIGINT         NOT NULL REFERENCES payslips (id) ON DELETE CASCADE,
    line_order     INTEGER        NOT NULL,
    line_type      VARCHAR(20)    NOT NULL,
    label          VARCHAR(150)   NOT NULL,
    amount         NUMERIC(14, 2) NOT NULL,
    running_total  NUMERIC(14, 2) NOT NULL,
    created_at     TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by     BIGINT,
    CONSTRAINT ck_payslip_lines_type CHECK (line_type IN ('BASE', 'OVERTIME', 'ALLOWANCE', 'DEDUCTION'))
);
