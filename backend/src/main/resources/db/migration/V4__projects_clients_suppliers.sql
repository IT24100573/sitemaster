-- ---- Clients ----------------------------------------------------------------
CREATE TABLE clients (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    contact_person  VARCHAR(100),
    email           VARCHAR(100) NOT NULL,
    phone           VARCHAR(15)  NOT NULL,
    address         VARCHAR(255),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT ck_clients_name CHECK (char_length(name) >= 2),
    CONSTRAINT ck_clients_email CHECK (email = LOWER(email)),
    CONSTRAINT ck_clients_phone CHECK (phone ~ '^(0[0-9]{9}|\+94[0-9]{9})$')
);

-- ---- Projects ---------------------------------------------------------------
CREATE TABLE projects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150)   NOT NULL,
    description     VARCHAR(2000),
    client_id       BIGINT         NOT NULL REFERENCES clients (id),
    manager_id      BIGINT         NOT NULL REFERENCES users (id),
    location        VARCHAR(255)   NOT NULL,
    latitude        NUMERIC(9, 6)  NOT NULL,
    longitude       NUMERIC(9, 6)  NOT NULL,
    start_date      DATE           NOT NULL,
    end_date        DATE           NOT NULL,
    budget          NUMERIC(14, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL DEFAULT 'PLANNED',
    progress        INTEGER        NOT NULL DEFAULT 0,
    cover_photo_id  BIGINT REFERENCES stored_files (id) ON DELETE SET NULL,
    completed_date  DATE,
    active          BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT ck_projects_name CHECK (char_length(name) >= 2),
    CONSTRAINT ck_projects_dates CHECK (end_date > start_date),
    CONSTRAINT ck_projects_budget CHECK (budget > 0),
    CONSTRAINT ck_projects_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_projects_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_projects_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_projects_status CHECK (status IN ('PLANNED', 'ACTIVE', 'DELAYED', 'COMPLETED', 'ARCHIVED'))
);

-- Project names are unique among projects that are not archived.
CREATE UNIQUE INDEX ux_projects_name_open ON projects (LOWER(name)) WHERE status <> 'ARCHIVED';
CREATE INDEX ix_projects_manager ON projects (manager_id);
CREATE INDEX ix_projects_status ON projects (status);

CREATE TABLE project_members (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT    NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id     BIGINT    NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by  BIGINT,
    CONSTRAINT uq_project_members UNIQUE (project_id, user_id)
);

CREATE INDEX ix_project_members_user ON project_members (user_id);

-- ---- Phases and milestones --------------------------------------------------
CREATE TABLE phases (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name         VARCHAR(100)   NOT NULL,
    description  VARCHAR(2000),
    start_date   DATE           NOT NULL,
    end_date     DATE           NOT NULL,
    budget       NUMERIC(14, 2) NOT NULL,
    status       VARCHAR(20)    NOT NULL DEFAULT 'NOT_STARTED',
    sort_order   INTEGER        NOT NULL DEFAULT 0,
    created_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT ck_phases_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_phases_budget CHECK (budget >= 0),
    CONSTRAINT ck_phases_status CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE INDEX ix_phases_project ON phases (project_id);

CREATE TABLE milestones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    phase_id        BIGINT REFERENCES phases (id) ON DELETE SET NULL,
    name            VARCHAR(150) NOT NULL,
    due_date        DATE         NOT NULL,
    completed       BOOLEAN      NOT NULL DEFAULT FALSE,
    completed_date  DATE,
    created_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT ck_milestones_completed CHECK (completed = (completed_date IS NOT NULL))
);

CREATE INDEX ix_milestones_project ON milestones (project_id, due_date);

-- ---- Tasks and sub-tasks ----------------------------------------------------
CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    phase_id      BIGINT        NOT NULL REFERENCES phases (id),
    title         VARCHAR(150)  NOT NULL,
    description   VARCHAR(2000),
    assignee_id   BIGINT REFERENCES users (id),
    priority      VARCHAR(10)   NOT NULL DEFAULT 'NORMAL',
    due_date      DATE          NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'TODO',
    progress      INTEGER       NOT NULL DEFAULT 0,
    completed_at  TIMESTAMP,
    created_at    TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT ck_tasks_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_tasks_done CHECK (status <> 'DONE' OR progress = 100)
);

CREATE INDEX ix_tasks_project ON tasks (project_id);
CREATE INDEX ix_tasks_phase ON tasks (phase_id);
CREATE INDEX ix_tasks_assignee ON tasks (assignee_id);

CREATE TABLE sub_tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT       NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    title         VARCHAR(150) NOT NULL,
    assignee_id   BIGINT REFERENCES users (id),
    status        VARCHAR(20)  NOT NULL DEFAULT 'TODO',
    due_date      DATE,
    completed_at  TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT ck_sub_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE'))
);

CREATE INDEX ix_sub_tasks_task ON sub_tasks (task_id);
CREATE INDEX ix_sub_tasks_assignee ON sub_tasks (assignee_id);

-- ---- Documents with versions ------------------------------------------------
CREATE TABLE project_documents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    title            VARCHAR(150) NOT NULL,
    category         VARCHAR(20)  NOT NULL,
    description      VARCHAR(500),
    current_version  INTEGER      NOT NULL DEFAULT 1,
    created_at       TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by       BIGINT,
    CONSTRAINT ck_project_documents_version CHECK (current_version >= 1),
    CONSTRAINT ck_project_documents_category CHECK (category IN
        ('DRAWING', 'CONTRACT', 'PERMIT', 'SPECIFICATION', 'REPORT', 'PHOTO', 'OTHER'))
);

CREATE INDEX ix_project_documents_project ON project_documents (project_id);

CREATE TABLE project_document_versions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT       NOT NULL REFERENCES project_documents (id) ON DELETE CASCADE,
    version_no      INTEGER      NOT NULL,
    file_id         BIGINT       NOT NULL REFERENCES stored_files (id),
    notes           VARCHAR(500),
    uploaded_by_id  BIGINT       NOT NULL REFERENCES users (id),
    created_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT uq_project_document_versions UNIQUE (document_id, version_no),
    CONSTRAINT ck_project_document_versions_no CHECK (version_no >= 1)
);

-- ---- Issues and risks -------------------------------------------------------
CREATE TABLE issues (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    issue_type      VARCHAR(10)   NOT NULL,
    title           VARCHAR(150)  NOT NULL,
    description     VARCHAR(2000) NOT NULL,
    severity        VARCHAR(10)   NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    reported_by_id  BIGINT        NOT NULL REFERENCES users (id),
    assigned_to_id  BIGINT REFERENCES users (id),
    due_date        DATE,
    resolution      VARCHAR(2000),
    resolved_at     TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT ck_issues_type CHECK (issue_type IN ('ISSUE', 'RISK')),
    CONSTRAINT ck_issues_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_issues_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_issues_resolution CHECK (status NOT IN ('RESOLVED', 'CLOSED') OR resolution IS NOT NULL)
);

CREATE INDEX ix_issues_project ON issues (project_id, status);

-- ---- Suppliers and applications ---------------------------------------------
CREATE TABLE suppliers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT REFERENCES users (id),
    name                 VARCHAR(150)  NOT NULL,
    registration_no      VARCHAR(50),
    contact_person       VARCHAR(100)  NOT NULL,
    email                VARCHAR(100)  NOT NULL,
    phone                VARCHAR(15)   NOT NULL,
    address              VARCHAR(255)  NOT NULL,
    material_categories  VARCHAR(1000) NOT NULL,
    active               BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at           TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by           BIGINT,
    CONSTRAINT uq_suppliers_user UNIQUE (user_id),
    CONSTRAINT ck_suppliers_email CHECK (email = LOWER(email)),
    CONSTRAINT ck_suppliers_phone CHECK (phone ~ '^(0[0-9]{9}|\+94[0-9]{9})$')
);

CREATE UNIQUE INDEX ux_suppliers_registration ON suppliers (UPPER(registration_no)) WHERE registration_no IS NOT NULL;

CREATE TABLE supplier_applications (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name              VARCHAR(150)  NOT NULL,
    registration_no           VARCHAR(50)   NOT NULL,
    contact_person            VARCHAR(100)  NOT NULL,
    email                     VARCHAR(100)  NOT NULL,
    phone                     VARCHAR(15)   NOT NULL,
    address                   VARCHAR(255)  NOT NULL,
    material_categories       VARCHAR(1000) NOT NULL,
    registration_document_id  BIGINT        NOT NULL REFERENCES stored_files (id),
    status                    VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    reviewed_by_id            BIGINT REFERENCES users (id),
    reviewed_at               TIMESTAMP,
    review_remarks            VARCHAR(500),
    supplier_id               BIGINT REFERENCES suppliers (id),
    created_at                TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at                TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by                BIGINT,
    CONSTRAINT ck_supplier_applications_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_supplier_applications_email CHECK (email = LOWER(email)),
    CONSTRAINT ck_supplier_applications_phone CHECK (phone ~ '^(0[0-9]{9}|\+94[0-9]{9})$')
);

-- At most one PENDING application per email and per registration number.
CREATE UNIQUE INDEX ux_supplier_applications_pending_email
    ON supplier_applications (LOWER(email)) WHERE status = 'PENDING';
CREATE UNIQUE INDEX ux_supplier_applications_pending_registration
    ON supplier_applications (UPPER(registration_no)) WHERE status = 'PENDING';
