-- ---- Audit log --------------------------------------------------------------
CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_name   VARCHAR(100)  NOT NULL,
    action       VARCHAR(60)   NOT NULL,
    module       VARCHAR(40)   NOT NULL,
    entity_type  VARCHAR(60),
    entity_id    BIGINT,
    description  VARCHAR(1000) NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT
);

CREATE INDEX ix_audit_logs_created_at ON audit_logs (created_at DESC);
CREATE INDEX ix_audit_logs_actor ON audit_logs (actor_id);
CREATE INDEX ix_audit_logs_module ON audit_logs (module);

-- ---- Notifications ----------------------------------------------------------
CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    event_type    VARCHAR(60)  NOT NULL,
    title         VARCHAR(150) NOT NULL,
    message       VARCHAR(500) NOT NULL,
    link          VARCHAR(255),
    is_read       BOOLEAN      NOT NULL DEFAULT FALSE,
    read_at       TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT
);

CREATE INDEX ix_notifications_recipient_unread ON notifications (recipient_id, is_read);
CREATE INDEX ix_notifications_recipient_created ON notifications (recipient_id, created_at DESC);

-- ---- Employees ---------------------------------------------------------------
CREATE SEQUENCE employee_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE employees (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  BIGINT        NOT NULL REFERENCES users (id),
    employee_no              VARCHAR(20)   NOT NULL,
    nic                      VARCHAR(12)   NOT NULL,
    date_of_birth            DATE          NOT NULL,
    address                  VARCHAR(255)  NOT NULL,
    join_date                DATE          NOT NULL,
    employment_type          VARCHAR(20)   NOT NULL,
    trade                    VARCHAR(50),
    daily_rate               NUMERIC(14, 2),
    monthly_salary           NUMERIC(14, 2),
    contract_amount          NUMERIC(14, 2),
    contract_start_date      DATE,
    contract_end_date        DATE,
    emergency_contact_name   VARCHAR(100),
    emergency_contact_phone  VARCHAR(15),
    created_at               TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at               TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by               BIGINT,
    CONSTRAINT uq_employees_user UNIQUE (user_id),
    CONSTRAINT uq_employees_no UNIQUE (employee_no),
    CONSTRAINT uq_employees_nic UNIQUE (nic),
    CONSTRAINT ck_employees_nic CHECK (nic ~ '^([0-9]{9}[VX]|[0-9]{12})$'),
    CONSTRAINT ck_employees_type CHECK (employment_type IN ('PERMANENT', 'CONTRACT', 'DAILY_WAGE')),
    CONSTRAINT ck_employees_amounts CHECK (
        (daily_rate IS NULL OR daily_rate > 0)
        AND (monthly_salary IS NULL OR monthly_salary > 0)
        AND (contract_amount IS NULL OR contract_amount > 0)),
    CONSTRAINT ck_employees_pay_terms CHECK (
        (employment_type = 'DAILY_WAGE' AND daily_rate IS NOT NULL)
        OR (employment_type = 'PERMANENT' AND monthly_salary IS NOT NULL)
        OR (employment_type = 'CONTRACT' AND contract_amount IS NOT NULL
            AND contract_start_date IS NOT NULL AND contract_end_date IS NOT NULL
            AND contract_end_date >= contract_start_date)),
    CONSTRAINT ck_employees_emergency_phone CHECK (
        emergency_contact_phone IS NULL OR emergency_contact_phone ~ '^(0[0-9]{9}|\+94[0-9]{9})$')
);

CREATE INDEX ix_employees_type ON employees (employment_type);

CREATE TABLE employee_documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    BIGINT       NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    document_type  VARCHAR(20)  NOT NULL,
    title          VARCHAR(100) NOT NULL,
    file_id        BIGINT       NOT NULL REFERENCES stored_files (id),
    created_at     TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by     BIGINT,
    CONSTRAINT ck_employee_documents_type CHECK (document_type IN ('NIC', 'CERTIFICATE', 'OTHER'))
);

CREATE INDEX ix_employee_documents_employee ON employee_documents (employee_id);
