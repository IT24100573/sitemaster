-- ---- Uploaded files ---------------------------------------------------------
CREATE TABLE stored_files (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stored_name    VARCHAR(64)  NOT NULL,
    original_name  VARCHAR(255) NOT NULL,
    content_type   VARCHAR(150) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    category       VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by     BIGINT,
    CONSTRAINT uq_stored_files_name UNIQUE (stored_name),
    CONSTRAINT ck_stored_files_size CHECK (size_bytes > 0),
    CONSTRAINT ck_stored_files_category CHECK (category IN ('IMAGE', 'DOCUMENT'))
);

-- ---- Users: phone, photo, session security version --------------------------
ALTER TABLE users
    ADD COLUMN phone            VARCHAR(15),
    ADD COLUMN profile_photo_id BIGINT REFERENCES stored_files (id) ON DELETE SET NULL,
    ADD COLUMN security_version INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_users_phone CHECK (phone IS NULL OR phone ~ '^(0[0-9]{9}|\+94[0-9]{9})$'),
    ADD CONSTRAINT ck_users_security_version CHECK (security_version >= 0);

-- ---- System settings (key/value, edited by Admin) ---------------------------
