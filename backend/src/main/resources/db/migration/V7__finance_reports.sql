-- =============================================================================
-- V7 (Phase 6): expense requests, petty cash, client invoices and receipts.
-- Payments (from Phase 4) can now settle an expense instead of a supplier invoice.
-- =============================================================================

-- ---- Expense requests (BaseRequest columns: status, requested_by_id, approved_by_id, remarks) ----
CREATE TABLE expense_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    phase_id         BIGINT         NOT NULL REFERENCES phases (id),
    category         VARCHAR(20)    NOT NULL,
    amount           NUMERIC(14, 2) NOT NULL,
    expense_date     DATE           NOT NULL,
    payee            VARCHAR(100)   NOT NULL,
    description      VARCHAR(500)   NOT NULL,
    receipt_file_id  BIGINT REFERENCES stored_files (id),
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    requested_by_id  BIGINT         NOT NULL REFERENCES users (id),
    approved_by_id   BIGINT REFERENCES users (id),
    remarks          VARCHAR(2000),
    decided_at       TIMESTAMP,
    paid_at          TIMESTAMP,
    created_at       TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at       TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by       BIGINT,
    CONSTRAINT ck_expense_requests_amount CHECK (amount > 0),
    CONSTRAINT ck_expense_requests_category CHECK (category IN ('MATERIALS', 'LABOUR', 'EQUIPMENT', 'OVERHEAD')),
    CONSTRAINT ck_expense_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'PAID')),
    CONSTRAINT ck_expense_requests_description CHECK (char_length(description) >= 5)
);

CREATE INDEX ix_expense_requests_project_status ON expense_requests (project_id, status);
CREATE INDEX ix_expense_requests_phase ON expense_requests (phase_id);

-- Payments settle either a supplier invoice or an expense.
ALTER TABLE payments ADD COLUMN expense_request_id BIGINT REFERENCES expense_requests (id);
ALTER TABLE payments ADD CONSTRAINT ck_payments_target
    CHECK (num_nonnulls(supplier_invoice_id, expense_request_id) = 1);
CREATE UNIQUE INDEX ux_payments_expense ON payments (expense_request_id) WHERE expense_request_id IS NOT NULL;

-- ---- Petty cash --------------------------------------------------------------------
CREATE TABLE petty_cash_funds (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    custodian_id  BIGINT         NOT NULL REFERENCES users (id),
    float_limit   NUMERIC(14, 2) NOT NULL,
    balance       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    active        BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT uq_petty_cash_funds_project UNIQUE (project_id),
    CONSTRAINT ck_petty_cash_funds_limit CHECK (float_limit > 0),
    CONSTRAINT ck_petty_cash_funds_balance CHECK (balance >= 0 AND balance <= float_limit)
);

CREATE TABLE petty_cash_transactions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_id             BIGINT         NOT NULL REFERENCES petty_cash_funds (id) ON DELETE CASCADE,
    type                VARCHAR(20)    NOT NULL,
    amount              NUMERIC(14, 2) NOT NULL,
    balance_after       NUMERIC(14, 2) NOT NULL,
    transaction_date    DATE           NOT NULL,
    description         VARCHAR(255)   NOT NULL,
    expense_request_id  BIGINT REFERENCES expense_requests (id),
    recorded_by_id      BIGINT         NOT NULL REFERENCES users (id),
    created_at          TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at          TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by          BIGINT,
    CONSTRAINT ck_petty_cash_tx_type CHECK (type IN ('TOP_UP', 'EXPENSE', 'ADJUSTMENT')),
    CONSTRAINT ck_petty_cash_tx_amount CHECK (amount <> 0),
    CONSTRAINT ck_petty_cash_tx_balance CHECK (balance_after >= 0),
    CONSTRAINT ck_petty_cash_tx_expense CHECK (type <> 'EXPENSE' OR expense_request_id IS NOT NULL)
);

CREATE INDEX ix_petty_cash_tx_fund ON petty_cash_transactions (fund_id, transaction_date DESC);

-- ---- Client invoices -------------------------------------------------------------------
CREATE SEQUENCE client_invoice_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE client_invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number  VARCHAR(20)    NOT NULL,
    project_id      BIGINT         NOT NULL REFERENCES projects (id),
    client_id       BIGINT         NOT NULL REFERENCES clients (id),
    issue_date      DATE           NOT NULL,
    due_date        DATE           NOT NULL,
    status          VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    tax_rate        NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    subtotal        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_amount      NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    paid_amount     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    notes           VARCHAR(500),
    issued_at       TIMESTAMP,
    created_at      TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT uq_client_invoices_number UNIQUE (invoice_number),
    CONSTRAINT ck_client_invoices_dates CHECK (due_date >= issue_date),
    CONSTRAINT ck_client_invoices_status CHECK (status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID')),
    CONSTRAINT ck_client_invoices_tax CHECK (tax_rate >= 0 AND tax_rate <= 30),
    CONSTRAINT ck_client_invoices_paid CHECK (paid_amount >= 0 AND paid_amount <= total)
);

CREATE INDEX ix_client_invoices_project ON client_invoices (project_id, status);

CREATE TABLE client_invoice_lines (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT         NOT NULL REFERENCES client_invoices (id) ON DELETE CASCADE,
    line_order   INTEGER        NOT NULL,
    description  VARCHAR(255)   NOT NULL,
    quantity     NUMERIC(14, 3) NOT NULL,
    unit_price   NUMERIC(14, 2) NOT NULL,
    line_total   NUMERIC(14, 2) NOT NULL,
    created_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT ck_client_invoice_lines_qty CHECK (quantity > 0),
    CONSTRAINT ck_client_invoice_lines_price CHECK (unit_price > 0)
);

CREATE TABLE client_payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    BIGINT         NOT NULL REFERENCES client_invoices (id),
    amount        NUMERIC(14, 2) NOT NULL,
    payment_date  DATE           NOT NULL,
    method        VARCHAR(20)    NOT NULL,
    reference_no  VARCHAR(50),
    notes         VARCHAR(500),
    received_by_id BIGINT        NOT NULL REFERENCES users (id),
    created_at    TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT ck_client_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_client_payments_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_client_payments_reference CHECK (method = 'CASH' OR reference_no IS NOT NULL)
);

CREATE UNIQUE INDEX ux_client_payments_reference
    ON client_payments (method, UPPER(reference_no)) WHERE method <> 'CASH';
