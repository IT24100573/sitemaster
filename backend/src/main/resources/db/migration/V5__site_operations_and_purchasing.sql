-- Permissions needed to maintain the catalogue and the equipment register.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN (VALUES
    ('ADMIN', 'MATERIAL', 'CREATE'), ('ADMIN', 'MATERIAL', 'EDIT'), ('ADMIN', 'MATERIAL', 'DELETE'),
    ('ADMIN', 'EQUIPMENT', 'CREATE'), ('ADMIN', 'EQUIPMENT', 'EDIT'), ('ADMIN', 'EQUIPMENT', 'DELETE'),
    ('ACCOUNTANT', 'MATERIAL', 'CREATE'), ('ACCOUNTANT', 'MATERIAL', 'EDIT'),
    ('PROJECT_MANAGER', 'EQUIPMENT', 'EDIT')
) AS g(role_name, module, action) ON r.name = g.role_name
JOIN permissions p ON p.module = g.module AND p.action = g.action
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- ---- Materials and site stock ---------------------------------------------
CREATE TABLE materials (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100)   NOT NULL,
    category     VARCHAR(50)    NOT NULL,
    unit         VARCHAR(20)    NOT NULL,
    unit_price   NUMERIC(14, 2) NOT NULL,
    description  VARCHAR(500),
    active       BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT ck_materials_price CHECK (unit_price >= 0)
);

CREATE UNIQUE INDEX ux_materials_name ON materials (LOWER(name));

CREATE TABLE site_stock (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    material_id  BIGINT         NOT NULL REFERENCES materials (id),
    quantity     NUMERIC(14, 3) NOT NULL DEFAULT 0,
    created_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT uq_site_stock UNIQUE (project_id, material_id),
    CONSTRAINT ck_site_stock_quantity CHECK (quantity >= 0)
);

-- ---- Equipment --------------------------------------------------------------
CREATE TABLE equipment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(30)  NOT NULL,
    name               VARCHAR(100) NOT NULL,
    category           VARCHAR(50)  NOT NULL,
    project_id         BIGINT REFERENCES projects (id) ON DELETE SET NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE',
    notes              VARCHAR(500),
    last_service_date  DATE,
    next_service_date  DATE,
    created_at         TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by         BIGINT,
    CONSTRAINT ck_equipment_status CHECK (status IN ('AVAILABLE', 'IN_USE', 'UNDER_MAINTENANCE', 'RETIRED')),
    CONSTRAINT ck_equipment_service CHECK (next_service_date IS NULL OR last_service_date IS NULL
                                           OR next_service_date >= last_service_date)
);

CREATE UNIQUE INDEX ux_equipment_code ON equipment (UPPER(code));

-- ---- Daily reports ------------------------------------------------------------
CREATE TABLE daily_reports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    submitted_by_id BIGINT        NOT NULL REFERENCES users (id),
    report_date     DATE          NOT NULL,
    work_done       VARCHAR(2000) NOT NULL,
    worker_count    INTEGER       NOT NULL,
    weather         VARCHAR(20)   NOT NULL,
    problems        VARCHAR(2000),
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    reviewed_by_id  BIGINT REFERENCES users (id),
    reviewed_at     TIMESTAMP,
    review_remarks  VARCHAR(500),
    created_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by      BIGINT,
    CONSTRAINT uq_daily_reports UNIQUE (project_id, submitted_by_id, report_date),
    CONSTRAINT ck_daily_reports_workers CHECK (worker_count >= 0),
    CONSTRAINT ck_daily_reports_work CHECK (char_length(work_done) >= 10),
    CONSTRAINT ck_daily_reports_weather CHECK (weather IN ('SUNNY', 'CLOUDY', 'RAINY', 'STORMY')),
    CONSTRAINT ck_daily_reports_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX ix_daily_reports_project_date ON daily_reports (project_id, report_date DESC);

CREATE TABLE daily_report_materials (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id    BIGINT         NOT NULL REFERENCES daily_reports (id) ON DELETE CASCADE,
    material_id  BIGINT         NOT NULL REFERENCES materials (id),
    quantity     NUMERIC(14, 3) NOT NULL,
    created_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT ck_daily_report_materials_qty CHECK (quantity > 0)
);

CREATE TABLE daily_report_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   BIGINT       NOT NULL REFERENCES daily_reports (id) ON DELETE CASCADE,
    file_id     BIGINT       NOT NULL REFERENCES stored_files (id),
    caption     VARCHAR(150),
    created_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by  BIGINT
);

-- ---- Material requests (BaseRequest columns: status, requested_by_id, approved_by_id, remarks) ----
CREATE TABLE material_requests (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          BIGINT         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    phase_id            BIGINT         NOT NULL REFERENCES phases (id),
    material_id         BIGINT         NOT NULL REFERENCES materials (id),
    quantity            NUMERIC(14, 3) NOT NULL,
    urgency             VARCHAR(10)    NOT NULL,
    required_by         DATE           NOT NULL,
    estimated_cost      NUMERIC(14, 2) NOT NULL,
    notes               VARCHAR(500),
    status              VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    requested_by_id     BIGINT         NOT NULL REFERENCES users (id),
    approved_by_id      BIGINT REFERENCES users (id),
    remarks             VARCHAR(2000),
    decided_at          TIMESTAMP,
    delivered_quantity  NUMERIC(14, 3),
    delivered_at        TIMESTAMP,
    delivered_by_id     BIGINT REFERENCES users (id),
    delivery_notes      VARCHAR(500),
    created_at          TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at          TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by          BIGINT,
    CONSTRAINT ck_material_requests_qty CHECK (quantity > 0),
    CONSTRAINT ck_material_requests_cost CHECK (estimated_cost >= 0),
    CONSTRAINT ck_material_requests_urgency CHECK (urgency IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT ck_material_requests_status CHECK (status IN
        ('PENDING', 'APPROVED', 'REJECTED', 'ORDERED', 'PAID', 'DELIVERED')),
    CONSTRAINT ck_material_requests_delivered CHECK (delivered_quantity IS NULL
        OR (delivered_quantity > 0 AND delivered_quantity <= quantity))
);

CREATE INDEX ix_material_requests_project_status ON material_requests (project_id, status);
CREATE INDEX ix_material_requests_phase ON material_requests (phase_id);

-- ---- Purchase orders, supplier invoices, payments ----------------------------------
CREATE SEQUENCE purchase_order_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE purchase_orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number               VARCHAR(20)    NOT NULL,
    material_request_id     BIGINT         NOT NULL REFERENCES material_requests (id),
    supplier_id             BIGINT         NOT NULL REFERENCES suppliers (id),
    project_id              BIGINT         NOT NULL REFERENCES projects (id),
    status                  VARCHAR(20)    NOT NULL DEFAULT 'SENT',
    order_date              DATE           NOT NULL,
    total_amount            NUMERIC(14, 2) NOT NULL,
    notes                   VARCHAR(500),
    responded_at            TIMESTAMP,
    decline_reason          VARCHAR(500),
    dispatched_at           TIMESTAMP,
    expected_delivery_date  DATE,
    paid_at                 TIMESTAMP,
    delivered_at            TIMESTAMP,
    created_at              TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at              TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by              BIGINT,
    CONSTRAINT uq_purchase_orders_number UNIQUE (po_number),
    CONSTRAINT ck_purchase_orders_total CHECK (total_amount > 0),
    CONSTRAINT ck_purchase_orders_status CHECK (status IN
        ('SENT', 'ACCEPTED', 'DECLINED', 'DISPATCHED', 'INVOICED', 'PAID', 'DELIVERED')),
    CONSTRAINT ck_purchase_orders_decline CHECK (status <> 'DECLINED' OR decline_reason IS NOT NULL)
);

-- A request can have many declined orders but only one that is not declined.
CREATE UNIQUE INDEX ux_purchase_orders_open_request
    ON purchase_orders (material_request_id) WHERE status <> 'DECLINED';
CREATE INDEX ix_purchase_orders_supplier ON purchase_orders (supplier_id, status);
CREATE INDEX ix_purchase_orders_project ON purchase_orders (project_id);

CREATE TABLE purchase_order_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id  BIGINT         NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    material_id        BIGINT         NOT NULL REFERENCES materials (id),
    quantity           NUMERIC(14, 3) NOT NULL,
    unit_price         NUMERIC(14, 2) NOT NULL,
    line_total         NUMERIC(14, 2) NOT NULL,
    created_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by         BIGINT,
    CONSTRAINT ck_purchase_order_items_qty CHECK (quantity > 0),
    CONSTRAINT ck_purchase_order_items_price CHECK (unit_price > 0),
    CONSTRAINT ck_purchase_order_items_total CHECK (line_total > 0)
);

CREATE TABLE supplier_invoices (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id  BIGINT         NOT NULL REFERENCES purchase_orders (id),
    supplier_id        BIGINT         NOT NULL REFERENCES suppliers (id),
    invoice_number     VARCHAR(50)    NOT NULL,
    invoice_date       DATE           NOT NULL,
    amount             NUMERIC(14, 2) NOT NULL,
    paid_amount        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    file_id            BIGINT         NOT NULL REFERENCES stored_files (id),
    status             VARCHAR(20)    NOT NULL DEFAULT 'ISSUED',
    created_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by         BIGINT,
    CONSTRAINT uq_supplier_invoices_po UNIQUE (purchase_order_id),
    CONSTRAINT uq_supplier_invoices_number UNIQUE (supplier_id, invoice_number),
    CONSTRAINT ck_supplier_invoices_amount CHECK (amount > 0),
    CONSTRAINT ck_supplier_invoices_paid CHECK (paid_amount >= 0 AND paid_amount <= amount),
    CONSTRAINT ck_supplier_invoices_status CHECK (status IN ('ISSUED', 'PARTIALLY_PAID', 'PAID'))
);

CREATE TABLE payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_invoice_id  BIGINT REFERENCES supplier_invoices (id),
    amount               NUMERIC(14, 2) NOT NULL,
    method               VARCHAR(20)    NOT NULL,
    reference_no         VARCHAR(50),
    payment_date         DATE           NOT NULL,
    notes                VARCHAR(500),
    paid_by_id           BIGINT         NOT NULL REFERENCES users (id),
    created_at           TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at           TIMESTAMP      NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by           BIGINT,
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CHEQUE')),
    CONSTRAINT ck_payments_reference CHECK (method = 'CASH' OR reference_no IS NOT NULL)
);

-- Bank transfer and cheque references must be unique.
CREATE UNIQUE INDEX ux_payments_reference ON payments (method, UPPER(reference_no)) WHERE method <> 'CASH';
