-- =============================================================================
-- V1: Roles, permissions, users and password reset tokens.
-- Every table carries the BaseEntity columns: id, created_at, updated_at, created_by.
-- Column lengths match the DTO @Size rules; CHECK constraints back up enums.
-- =============================================================================

CREATE TABLE roles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(30)  NOT NULL,
    display_name  VARCHAR(50)  NOT NULL,
    description   VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by    BIGINT,
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_name CHECK (name IN ('ADMIN', 'PROJECT_MANAGER', 'SITE_ENGINEER', 'WORKER',
                                             'HR_MANAGER', 'ACCOUNTANT', 'SUPPLIER'))
);

CREATE TABLE permissions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module       VARCHAR(40)  NOT NULL,
    action       VARCHAR(20)  NOT NULL,
    description  VARCHAR(255),
    created_at   TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by   BIGINT,
    CONSTRAINT uq_permissions_module_action UNIQUE (module, action),
    CONSTRAINT ck_permissions_action CHECK (action IN ('VIEW', 'CREATE', 'EDIT', 'APPROVE', 'DELETE')),
    CONSTRAINT ck_permissions_module CHECK (module IN (
        'USER', 'ROLE', 'EMPLOYEE', 'PROJECT', 'TASK', 'DAILY_REPORT', 'MATERIAL', 'MATERIAL_REQUEST',
        'PURCHASE_ORDER', 'SUPPLIER', 'SUPPLIER_INVOICE', 'EQUIPMENT', 'ISSUE', 'DOCUMENT', 'ATTENDANCE',
        'LEAVE', 'PAYROLL', 'EXPENSE', 'PAYMENT', 'CLIENT', 'INVOICE', 'REPORT', 'SETTINGS', 'AUDIT_LOG'))
);

CREATE TABLE role_permissions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id        BIGINT    NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id  BIGINT    NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    created_at     TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at     TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by     BIGINT,
    CONSTRAINT uq_role_permissions UNIQUE (role_id, permission_id)
);

CREATE TABLE users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name              VARCHAR(100) NOT NULL,
    email                  VARCHAR(100) NOT NULL,
    password_hash          VARCHAR(100) NOT NULL,
    role_id                BIGINT       NOT NULL REFERENCES roles (id),
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts  INTEGER      NOT NULL DEFAULT 0,
    locked_until           TIMESTAMP,
    last_login_at          TIMESTAMP,
    created_at             TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at             TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by             BIGINT,
    CONSTRAINT ck_users_full_name_length CHECK (char_length(full_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_users_email_lowercase CHECK (email = LOWER(email)),
    CONSTRAINT ck_users_failed_attempts CHECK (failed_login_attempts >= 0)
);

-- Case-insensitive uniqueness of email (also used by findByEmailIgnoreCase).
CREATE UNIQUE INDEX ux_users_email_lower ON users (LOWER(email));
CREATE INDEX ix_users_role ON users (role_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    used_at     TIMESTAMP,
    created_at  TIMESTAMP   NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at  TIMESTAMP   NOT NULL DEFAULT LOCALTIMESTAMP,
    created_by  BIGINT,
    CONSTRAINT uq_password_reset_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_reset_tokens_hash_length CHECK (char_length(token_hash) = 64)
);

CREATE INDEX ix_password_reset_tokens_user ON password_reset_tokens (user_id);
